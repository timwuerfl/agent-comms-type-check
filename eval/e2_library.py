"""E1/E2: verify every protocol in the library, emit kernel-checked Lean proofs, time everything.

Writes eval/results/library.json and lean/Protocols/*.lean (+ lean/Protocols.lean).
"""
from __future__ import annotations

import glob
import json
import os
import re
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "python"))

from swarmgate.check import emit_lean, influence_bits, verify  # noqa: E402
from swarmgate.dsl import compile_file  # noqa: E402
from swarmgate.project import with_locals  # noqa: E402

LEAN = os.path.join(ROOT, "lean")
ELAN = os.path.expanduser("~/.elan/bin")


def main() -> None:
    rows = []
    os.makedirs(os.path.join(LEAN, "Protocols"), exist_ok=True)
    names = []
    for f in sorted(glob.glob(os.path.join(ROOT, "protocols", "*.sg"))):
        P = compile_file(f)
        with_locals(P)
        t0 = time.perf_counter()
        r = verify(P)
        t_check = time.perf_counter() - t0
        name = re.sub(r"[^A-Za-z0-9]", "", P.name)
        lean_src = emit_lean(P, name)
        path = os.path.join(LEAN, "Protocols", f"{name}.lean")
        with open(path, "w") as fh:
            fh.write(lean_src)
        names.append(name)
        env = dict(os.environ, PATH=ELAN + ":" + os.environ["PATH"])
        t0 = time.perf_counter()
        kp = subprocess.run(["lake", "env", "lean", path], cwd=LEAN, capture_output=True, text=True, env=env)
        t_kernel = time.perf_counter() - t0
        n_thm = lean_src.count("_certified : ")
        infl = influence_bits(P) if P.ifc else {}
        rows.append({
            "file": os.path.basename(f), "name": P.name, "roles": len(P.roles), "states": len(P.states),
            "transitions": sum(len(s) for s in P.states),
            "properties": [(p["name"], p["verified"]) for p in r["properties"]],
            "ifc": r.get("ifc", {}).get("verified"),
            "ifc_counterexample": r.get("ifc", {}).get("counterexample"),
            "no_stuck": r["noStuck"]["verified"], "completion": r["completion"]["verified"],
            "bounded": r["bounded"]["verified"], "max_messages": r["bounded"]["maxMessages"],
            "decentralised": r.get("decentralised", {}).get("verified"),
            "decentralised_configs": r.get("decentralised", {}).get("configurations"),
            "check_ms": round(1000 * t_check, 1), "kernel_s": round(t_kernel, 2),
            "kernel_ok": kp.returncode == 0, "kernel_theorems": n_thm,
            "kernel_errors": kp.stdout[-2000:] if kp.returncode else "",
            "influence_bits": {k: (None if v == float("inf") else v) for k, v in infl.items()},
        })
        print(f"{P.name:24s} states={len(P.states):3d} check={1000*t_check:7.1f}ms kernel={t_kernel:5.2f}s "
              f"ok={kp.returncode == 0} thms={n_thm} ifc={rows[-1]['ifc']} dec={rows[-1]['decentralised']}")
    with open(os.path.join(LEAN, "Protocols.lean"), "w") as fh:
        fh.write("-- Kernel-checked guarantees for every protocol in protocols/ (generated by eval/e2_library.py)\n")
        for n in names:
            fh.write(f"import Protocols.{n}\n")
    os.makedirs(os.path.join(ROOT, "eval", "results"), exist_ok=True)
    with open(os.path.join(ROOT, "eval", "results", "library.json"), "w") as fh:
        json.dump(rows, fh, indent=1)


if __name__ == "__main__":
    main()
